#!/bin/bash
# Скрипт для перезапуска AI-стека (остановка + запуск)

# Переход в папку со скриптом:
cd "$(cd "$(dirname "$0")" && pwd)"

echo "Перезапуск AI стека..."
echo ""


####################################################################
# Предзагрузка образов для параллельной сборки (ускоряет процесс): #
####################################################################

echo "📥 Предзагрузка Docker образов..."

# Составление списка образов:
IMAGES=$(
    {
        grep "^FROM" */Dockerfile | awk '{print $2}';
        grep "image:" docker-compose.yaml | awk '{print $2}';
    } | sort -u
)

# Параллельное скачивание образов в фоне:
for img in $IMAGES; do
    docker pull "$img" &
done

# Ожидание завершения всех фоновых загрузок:
wait

echo "✅ Все образы загружены"
echo ""


# Останавливаем сервисы:
"./stop.sh"
# Запускаем сервисы:
"./run.sh"
